import SwiftUI

extension Color {
    init?(hex: String?) {
        guard let hex, hex.hasPrefix("#"), let value = Int(hex.dropFirst(), radix: 16) else {
            return nil
        }
        self.init(
            red: Double((value >> 16) & 0xFF) / 255,
            green: Double((value >> 8) & 0xFF) / 255,
            blue: Double(value & 0xFF) / 255
        )
    }
}
